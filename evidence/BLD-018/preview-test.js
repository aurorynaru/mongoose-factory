async (page) => {
  const base = 'http://127.0.0.1:8765/';
  const out = [];
  const errs = [];
  page.on('pageerror', e => errs.push(String(e)));
  const ok = (name, cond) => out.push((cond ? 'PASS ' : 'FAIL ') + name);
  await page.goto(base + 'FX_ServiceDeskLogin/index.html');
  await page.evaluate(() => sessionStorage.clear());
  await page.reload();
  await page.click('#FX_InSubmit');
  ok('empty sign-in shows 2 field errors', await page.locator('.FX_Err').count() === 2);
  ok('focus moves to username', await page.evaluate(() => document.activeElement.id) === 'FX_InUser');
  await page.fill('#FX_InUser', 'sam.lee'); await page.fill('#FX_InPass', 'wrong-password');
  await page.click('#FX_InSubmit');
  await page.waitForSelector('#FX_Alert:not([hidden])');
  ok('wrong password: generic message', (await page.textContent('#FX_AlertText')) === 'Username or password is incorrect. Check both and try again.');
  ok('password cleared after failure', (await page.inputValue('#FX_InPass')) === '');
  await page.fill('#FX_InUser', 'nobody.here'); await page.fill('#FX_InPass', 'whatever123');
  await page.click('#FX_InSubmit'); await page.waitForTimeout(700);
  ok('unknown user: same message', (await page.textContent('#FX_AlertText')) === 'Username or password is incorrect. Check both and try again.');
  await page.fill('#FX_InUser', 'Sam.Lee '); await page.fill('#FX_InPass', 'correct-horse');
  await page.click('#FX_InSubmit');
  await page.waitForURL(/FX_ServiceDesk\/index.html/, { timeout: 5000 });
  await page.waitForSelector('#FX_SignOut', { timeout: 5000 });
  ok('signed in (mixed case) -> app opens', true);
  ok('no Who are you picker', await page.locator('#FX_MePick').count() === 0);
  ok('gate hidden', await page.locator('#FX_Gate').isHidden());
  ok('sidebar shows the signed-in user', (await page.textContent('#FX_Me')).includes('sam.lee'));
  const logs = [];
  page.on('console', m => logs.push(m.text()));
  await page.click('#FX_Refresh'); await page.waitForTimeout(800);
  const tok = await page.evaluate(() => sessionStorage.getItem('FX_ServiceDesk.session'));
  ok('token not in console', logs.length > 0 && !logs.some(l => l.includes(tok)));
  await page.click('#FX_SignOut');
  await page.waitForSelector('#FX_Gate:not([hidden])');
  ok('sign out shows gate with "signed out"', (await page.textContent('#FX_GateText')).includes('signed out'));
  ok('token removed', await page.evaluate(() => sessionStorage.getItem('FX_ServiceDesk.session')) === null);
  ok('app inert', await page.evaluate(() => document.getElementById('FX_App').hasAttribute('inert')));
  await page.click('#FX_GateSignIn');
  await page.waitForURL(/FX_ServiceDeskLogin/);
  await page.waitForTimeout(300);
  ok('back on login, form shown', await page.locator('#FX_Forms').isVisible());
  await page.click('#FX_TabUp');
  ok('create tab pressed', (await page.getAttribute('#FX_TabUp', 'aria-pressed')) === 'true');
  await page.fill('#FX_UpUser', 'Bad Name!'); await page.fill('#FX_UpPass', 'short'); await page.fill('#FX_UpPass2', 'other');
  await page.click('#FX_UpSubmit');
  ok('signup client errors: 4', await page.locator('#FX_SignUp .FX_Err').count() === 4);
  await page.fill('#FX_UpUser', 'agent.anna'); await page.fill('#FX_UpName', 'Anna Imposter');
  await page.fill('#FX_UpPass', 'long-enough-pass'); await page.fill('#FX_UpPass2', 'long-enough-pass');
  await page.click('#FX_UpSubmit'); await page.waitForSelector('#FX_UpUser_err');
  ok('existing name refused', (await page.textContent('#FX_UpUser_err')).includes('taken'));
  ok('strength meter good', (await page.getAttribute('#FX_MeterBar', 'class')) === 'is-good');
  await page.fill('#FX_UpUser', 'fx.test.agent'); await page.fill('#FX_UpName', 'Test Agent'); await page.fill('#FX_UpTeam', 'Service Desk');
  await page.click('#FX_UpSubmit');
  await page.waitForURL(/FX_ServiceDesk\/index.html/, { timeout: 5000 });
  await page.waitForSelector('#FX_SignOut');
  ok('new account lands in app', (await page.textContent('#FX_Me')).includes('fx.test.agent'));
  await page.goto(base + 'FX_ServiceDesk/index.html?expire=1');
  await page.waitForSelector('#FX_Gate:not([hidden])');
  ok('expired session -> gate', (await page.textContent('#FX_GateText')).includes('session has ended'));
  await page.evaluate(() => sessionStorage.clear());
  await page.goto(base + 'FX_ServiceDesk/index.html');
  await page.waitForSelector('#FX_Gate:not([hidden])');
  ok('no token -> gate', true);
  await page.goto(base + 'FX_ServiceDesk/index.html?as=agent.anna');
  await page.waitForSelector('#FX_SignOut');
  ok('?as session loads app', true);
  await page.goto(base + 'FX_ServiceDesk/index.html?as=agent.anna&empty=1');
  await page.waitForSelector('#FX_SignOut');
  // A first call that arrives without its argument (tenant, step 8) is retried, not shown as signed out.
  await page.goto(base + 'FX_ServiceDesk/index.html?as=agent.anna&dropfirst=1');
  await page.waitForSelector('#FX_SignOut', { timeout: 8000 });
  ok('app: dropped first argument -> retried, app loads', await page.locator('#FX_Gate').isHidden());
  await page.goto(base + 'FX_ServiceDeskLogin/index.html?dropfirst=1');
  await page.waitForSelector('#FX_Resume:not([hidden])', { timeout: 8000 });
  ok('login: dropped first argument -> retried, token kept',
    !!(await page.evaluate(() => sessionStorage.getItem('FX_ServiceDesk.session'))));
  ok('no page errors', errs.length === 0);
  return out.join('\n') + '\nerrors: ' + JSON.stringify(errs);
}
